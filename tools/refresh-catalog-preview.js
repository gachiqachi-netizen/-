// Run: node tools/refresh-catalog-preview.js [http://localhost:8801]
const fs=require('node:fs'),path=require('node:path')
async function refresh(base=process.env.CATALOG_API_BASE||'http://127.0.0.1:8801',output=path.resolve(__dirname,'../miniprogram/utils/catalog-preview.js')) {
  const url=new URL('/api/catalog',base)
  if(!['http:','https:'].includes(url.protocol))throw new Error('目录地址必须是 HTTP 或 HTTPS')
  const response=await fetch(url,{signal:AbortSignal.timeout(10000)})
  if(!response.ok)throw new Error('目录请求失败：'+response.status)
  const catalog=await response.json()
  if(!catalog||!Array.isArray(catalog.beads)||!catalog.beads.length)throw new Error('目录为空或格式不正确')
  // Only public catalog collections, never user data or server credentials.
  const publicData={beads:catalog.beads.map(b=>({...b,points:Array.isArray(b.points)?b.points:[],safety:b.safety||''})),templates:catalog.templates||[],banners:catalog.banners||[],ai:{enabled:false,reason:'离线示例'}}
  const text='// Generated by tools/refresh-catalog-preview.js; development fallback only.\nmodule.exports = '+JSON.stringify(publicData,null,2)+'\n'
  fs.writeFileSync(output+'.tmp',text);fs.renameSync(output+'.tmp',output)
  return publicData.beads.length
}
if(require.main===module)refresh(process.argv[2]).then(n=>console.log('已更新离线目录：'+n+'种材料')).catch(e=>{console.error(e.message);process.exitCode=1})
module.exports={refresh}
